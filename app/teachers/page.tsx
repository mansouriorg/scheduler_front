'use client';

import { useState, useEffect } from 'react';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import { Notice, type NoticeMessage } from '@/components/notice';
import { StatusRow } from '@/components/status-message';
import { TABLE_CARDS } from '@/lib/table-cards';
import { NoMatchRow, TableSearchBar } from '@/components/table-search';
import { filterBySearch, noMatchText, searchCount } from '@/lib/table-search';
import { getErrorMessage } from '@/lib/api-error';
import { ConfirmDialog } from '@/components/confirm-dialog';
import { Clock, Pencil, Trash2 } from 'lucide-react';
import {
  DAYS,
  END_TIMES,
  START_TIMES,
  dayName,
  nextTimeOff,
  sortTimesOff,
  timeOffLabel,
  timesOffProblem,
  type TimeOff,
} from '@/lib/teacher-times';
import { maximumHint, weeklyHoursLines, type WeeklyHours } from '@/lib/teacher-hours';
import { api } from '@/lib/api'; 

// 1. Zod Validation Schema (Cleaned up for strict TypeScript matching)
const teacherSchema = z.object({
  name: z.string().min(2, 'Name must be at least 2 characters'),
  department: z.string().min(2, 'Department is required'),
  maxHoursPerWeek: z.number().min(1, 'Must be at least 1 hour').max(60, 'Cannot exceed 60 hours'), // Removed coerce
  timePreference: z.enum(['MORNING', 'AFTERNOON', 'EVENING', 'NO_PREFERENCE']),
});

type TeacherFormValues = z.infer<typeof teacherSchema>;

// Extend the type to include the ID generated by the database, the times each
// week when the teacher cannot teach, and how long they teach a week in each term
// in which they have classes (see lib/teacher-hours.ts)
type Teacher = TeacherFormValues & { id: string; unavailability?: TimeOff[]; weeklyHours?: WeeklyHours[] };

// The look of the lists in the Times off form.
const TIME_OFF_FIELD =
  'w-full rounded-lg border border-gray-500 bg-white px-3 py-2.5 text-base text-gray-900 shadow-sm focus:border-blue-600 sm:text-sm';

// Where the box of the table is narrower than 42rem, each teacher is shown as a
// card (see lib/table-cards.ts).
const cards = TABLE_CARDS['2xl'];

export default function TeachersPage() {
  const [teachers, setTeachers] = useState<Teacher[]>([]);
  const [isSubmitting, setIsSubmitting] = useState(false);
  
  // This state acts as a trigger. Whenever it changes, we re-fetch the list!
  const [refreshTrigger, setRefreshTrigger] = useState(0);
  const [isLoading, setIsLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [notice, setNotice] = useState<NoticeMessage | null>(null);
  // What is typed in the search box above the list (see lib/table-search.ts).
  const [search, setSearch] = useState('');
  // The teacher shown in the form for changes (null: the form adds a new teacher),
  // and the teacher waiting in the "Delete?" window.
  const [editing, setEditing] = useState<Teacher | null>(null);
  const [toDelete, setToDelete] = useState<Teacher | null>(null);
  const [isDeleting, setIsDeleting] = useState(false);
  // The teacher whose times off are shown in the form (null: none), and those
  // times off as they are being changed.
  const [timesOffOf, setTimesOffOf] = useState<Teacher | null>(null);
  const [timesOff, setTimesOff] = useState<TimeOff[]>([]);
  const [isSavingTimes, setIsSavingTimes] = useState(false);

  const {
    register,
    handleSubmit,
    reset,
    setFocus,
    formState: { errors },
  } = useForm<TeacherFormValues>({
    resolver: zodResolver(teacherSchema),
    defaultValues: {
      timePreference: 'NO_PREFERENCE',
    },
  });

  // 2. Fetch Teachers using Axios API client
  useEffect(() => {
    const fetchTeachers = async () => {
      try {
        const data = await api.getTeachers(); 
        setTeachers(data);
        setLoadError(null);
      } catch (error) {
        console.error('Failed to fetch teachers. Is the backend running?', error);
        setLoadError(getErrorMessage(error));
      } finally {
        setIsLoading(false);
      }
    };

    fetchTeachers();
  }, [refreshTrigger]);

  const retryLoad = () => {
    setIsLoading(true);
    setLoadError(null);
    setRefreshTrigger((prev) => prev + 1);
  };

  // 3. Handle Form Submission using Axios API client
  const onSubmit = async (data: TeacherFormValues) => {
    setIsSubmitting(true);
    setNotice(null);
    try {
      if (editing) {
        await api.updateTeacher(editing.id, data);
        setNotice({ type: 'success', text: `${data.name} was updated.` });
        setEditing(null);
      } else {
        await api.createTeacher(data);
        setNotice({ type: 'success', text: 'Teacher saved.' });
      }
      reset(); // Clear the form inputs
      setRefreshTrigger((prev) => prev + 1); // Trigger the useEffect to refresh the table
    } catch (error) {
      console.error(error);
      setNotice({ type: 'error', text: `Could not save the teacher. ${getErrorMessage(error)}` });
    } finally {
      setIsSubmitting(false);
    }
  };

  // Puts a teacher from the table into the form, to change it.
  const startEdit = (teacher: Teacher) => {
    setTimesOffOf(null);
    setEditing(teacher);
    setNotice(null);
    reset({
      name: teacher.name,
      department: teacher.department,
      maxHoursPerWeek: teacher.maxHoursPerWeek,
      timePreference: teacher.timePreference,
    }, { keepDefaultValues: true }); // Cancel and Save then empty the form again
    // reset attaches the fields again on the next render; focus after that.
    setTimeout(() => setFocus('name'), 0);
  };

  const cancelEdit = () => {
    setEditing(null);
    reset();
  };

  // Shows the times off of a teacher in the form. Only one form is open at a
  // time, so Edit is left first.
  const startTimesOff = (teacher: Teacher) => {
    if (editing) cancelEdit();
    setNotice(null);
    setTimesOffOf(teacher);
    setTimesOff(sortTimesOff(teacher.unavailability ?? []));
    // The form appears on the next render; move to its title after that.
    setTimeout(() => document.getElementById('times-off-title')?.focus(), 0);
  };

  const changeTimeOff = (index: number, change: Partial<TimeOff>) =>
    setTimesOff((prev) => prev.map((time, at) => (at === index ? { ...time, ...change } : time)));

  // What is wrong with the times off in the form, shown under them; null: nothing.
  const timesOffError = timesOffProblem(timesOff);

  // While a teacher is changed: the lowest maximum hours brain_server accepts, and
  // why, shown under that field; null: no limit (no classes, or a new teacher).
  const hoursHint = editing ? maximumHint(editing.name, editing.weeklyHours) : null;

  // Saves the times off, all together. brain_server refuses, and says why, when
  // a class of the teacher that is already in the timetable falls in one; the
  // form then stays open.
  const saveTimesOff = async () => {
    if (timesOffOf === null || timesOffError !== null) return;
    setIsSavingTimes(true);
    setNotice(null);
    try {
      await api.setTeacherTimesOff(
        timesOffOf.id,
        timesOff.map(({ dayOfWeek, startTime, endTime }) => ({ dayOfWeek, startTime, endTime })),
      );
      setNotice({ type: 'success', text: `The times off of ${timesOffOf.name} were saved.` });
      setTimesOffOf(null);
      setRefreshTrigger((prev) => prev + 1);
    } catch (error) {
      console.error(error);
      setNotice({ type: 'error', text: `Could not save the times off. ${getErrorMessage(error)}` });
    } finally {
      setIsSavingTimes(false);
    }
  };

  // Runs when "Delete" is confirmed in the window. The server refuses while the
  // teacher has classes; its message (why, and what to do) is shown as it is.
  const confirmDelete = async () => {
    if (toDelete === null) return;
    setIsDeleting(true);
    try {
      await api.deleteTeacher(toDelete.id);
      setNotice({ type: 'success', text: `${toDelete.name} was deleted.` });
      if (editing?.id === toDelete.id) cancelEdit();
      if (timesOffOf?.id === toDelete.id) setTimesOffOf(null);
      setRefreshTrigger((prev) => prev + 1);
    } catch (error) {
      console.error(error);
      setNotice({ type: 'error', text: `Could not delete ${toDelete.name}. ${getErrorMessage(error)}` });
    } finally {
      setIsDeleting(false);
      setToDelete(null);
    }
  };

  // The teachers that have what is typed in the search box, in their name or department.
  const shownTeachers = filterBySearch(teachers, search, (teacher) => [teacher.name, teacher.department]);

  return (
    <div className="min-h-screen bg-gray-50 p-4 sm:p-6 lg:p-8">
      <div className="max-w-7xl mx-auto">
        <h1 className="mb-6 text-2xl font-bold text-gray-900 sm:mb-8 sm:text-3xl">Teacher Management</h1>
        <Notice message={notice} onDismiss={setNotice} />
        <ConfirmDialog
          open={toDelete !== null}
          title={`Delete ${toDelete?.name ?? 'this teacher'}?`}
          message="This cannot be undone. A teacher who teaches classes cannot be deleted; you will see a message instead."
          confirmLabel={isDeleting ? 'Deleting...' : 'Delete'}
          busy={isDeleting}
          onConfirm={confirmDelete}
          onCancel={() => setToDelete(null)}
        />

        <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
          
          {/* LEFT COLUMN: THE FORM */}
          <div className="lg:col-span-1 bg-white p-6 rounded-xl shadow-sm border border-gray-100 h-fit">
            {timesOffOf ? (
              <form
                onSubmit={(event) => {
                  event.preventDefault();
                  void saveTimesOff();
                }}
                className="space-y-4"
              >
                <div>
                  <h2 id="times-off-title" tabIndex={-1} className="text-xl font-semibold text-gray-800 outline-none">
                    Times off: {timesOffOf.name}
                  </h2>
                  <p className="mt-2 text-sm text-gray-600">
                    The times each week when {timesOffOf.name} cannot teach. Generate keeps their classes out of
                    these times. A time off cannot cover a class of theirs that is already in the timetable.
                  </p>
                </div>
                {timesOff.length === 0 && (
                  <p className="text-sm text-gray-700">No times off: {timesOffOf.name} can teach at any time.</p>
                )}
                {timesOff.map((time, index) => (
                  <fieldset key={index} className="rounded-lg border border-gray-200 p-3">
                    <legend className="px-1 text-sm font-medium text-gray-700">Time off {index + 1}</legend>
                    <div className="grid grid-cols-2 gap-2">
                      <div className="col-span-2">
                        <label htmlFor={`time-off-day-${index}`} className="mb-1 block text-xs font-medium text-gray-700">Day</label>
                        <select
                          id={`time-off-day-${index}`}
                          value={time.dayOfWeek}
                          onChange={(event) => changeTimeOff(index, { dayOfWeek: event.target.value })}
                          className={TIME_OFF_FIELD}
                        >
                          {DAYS.map((day) => (
                            <option key={day} value={day}>{dayName(day)}</option>
                          ))}
                        </select>
                      </div>
                      <div>
                        <label htmlFor={`time-off-start-${index}`} className="mb-1 block text-xs font-medium text-gray-700">From</label>
                        <select
                          id={`time-off-start-${index}`}
                          value={time.startTime}
                          onChange={(event) => changeTimeOff(index, { startTime: event.target.value })}
                          className={TIME_OFF_FIELD}
                        >
                          {START_TIMES.map((clock) => (
                            <option key={clock} value={clock}>{clock}</option>
                          ))}
                        </select>
                      </div>
                      <div>
                        <label htmlFor={`time-off-end-${index}`} className="mb-1 block text-xs font-medium text-gray-700">To</label>
                        <select
                          id={`time-off-end-${index}`}
                          value={time.endTime}
                          onChange={(event) => changeTimeOff(index, { endTime: event.target.value })}
                          className={TIME_OFF_FIELD}
                        >
                          {END_TIMES.map((clock) => (
                            <option key={clock} value={clock}>{clock}</option>
                          ))}
                        </select>
                      </div>
                    </div>
                    <button
                      type="button"
                      onClick={() => setTimesOff((prev) => prev.filter((_, at) => at !== index))}
                      aria-label={`Remove time off ${index + 1}`}
                      className="mt-2 rounded-md px-2 py-1.5 text-sm font-medium text-red-700 transition-colors hover:bg-red-50"
                    >
                      Remove
                    </button>
                  </fieldset>
                ))}
                <button
                  type="button"
                  onClick={() => setTimesOff((prev) => [...prev, nextTimeOff(prev)])}
                  className="w-full rounded-lg border border-dashed border-gray-500 bg-white px-4 py-2.5 text-sm font-semibold text-gray-700 transition-colors hover:bg-gray-50"
                >
                  Add a time off
                </button>
                {timesOffError && (
                  <p aria-live="polite" className="text-sm font-medium text-red-700">{timesOffError}</p>
                )}
                <div className="mt-6 space-y-3">
                  <button
                    type="submit"
                    disabled={isSavingTimes || timesOffError !== null}
                    className="w-full rounded-lg bg-blue-600 px-4 py-2.5 text-sm font-semibold text-white shadow-sm transition-colors hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"
                  >
                    {isSavingTimes ? 'Saving...' : 'Save Times Off'}
                  </button>
                  <button
                    type="button"
                    onClick={() => setTimesOffOf(null)}
                    className="w-full rounded-lg border border-gray-500 bg-white px-4 py-2.5 text-sm font-semibold text-gray-700 shadow-sm transition-colors hover:bg-gray-50"
                  >
                    Cancel
                  </button>
                </div>
              </form>
            ) : (
            <>
            <h2 className="text-xl font-semibold mb-6 text-gray-800">{editing ? `Edit ${editing.name}` : 'Add New Teacher'}</h2>
            
            <form onSubmit={handleSubmit(onSubmit)} className="space-y-4">
              <div>
                <label htmlFor="teacher-name" className="block text-sm font-medium text-gray-700 mb-1">Full Name</label>
                <input
                  {...register('name')}
                  id="teacher-name"
                  aria-invalid={errors.name ? true : undefined}
                  aria-describedby={errors.name ? 'teacher-name-error' : undefined}
                  className="w-full rounded-lg border border-gray-500 bg-white px-3 py-2.5 text-base text-gray-900 shadow-sm placeholder:text-gray-500 focus:border-blue-600 sm:text-sm"
                  placeholder="e.g. Dr. Jane Smith"
                />
                {errors.name && <p id="teacher-name-error" className="mt-1 text-xs font-medium text-red-700">{errors.name.message}</p>}
              </div>

              <div>
                <label htmlFor="teacher-department" className="block text-sm font-medium text-gray-700 mb-1">Department</label>
                <input
                  {...register('department')}
                  id="teacher-department"
                  aria-invalid={errors.department ? true : undefined}
                  aria-describedby={errors.department ? 'teacher-department-error' : undefined}
                  className="w-full rounded-lg border border-gray-500 bg-white px-3 py-2.5 text-base text-gray-900 shadow-sm placeholder:text-gray-500 focus:border-blue-600 sm:text-sm"
                  placeholder="e.g. Computer Science"
                />
                {errors.department && <p id="teacher-department-error" className="mt-1 text-xs font-medium text-red-700">{errors.department.message}</p>}
              </div>

              <div>
                <label htmlFor="teacher-max-hours-per-week" className="block text-sm font-medium text-gray-700 mb-1">Max Teaching Hours / Week</label>
                <input
                  type="number"
                  // Added valueAsNumber: true to ensure RHF passes a pure number to Zod
                  {...register('maxHoursPerWeek', { valueAsNumber: true })}
                  id="teacher-max-hours-per-week"
                  aria-invalid={errors.maxHoursPerWeek ? true : undefined}
                  aria-describedby={
                    hoursHint
                      ? errors.maxHoursPerWeek ? 'teacher-max-hours-per-week-hint teacher-max-hours-per-week-error' : 'teacher-max-hours-per-week-hint'
                      : errors.maxHoursPerWeek ? 'teacher-max-hours-per-week-error' : undefined
                  }
                  className="w-full rounded-lg border border-gray-500 bg-white px-3 py-2.5 text-base text-gray-900 shadow-sm placeholder:text-gray-500 focus:border-blue-600 sm:text-sm"
                  placeholder="e.g. 18"
                />
                {hoursHint && (
                  <p id="teacher-max-hours-per-week-hint" className="mt-1 text-xs text-gray-600">{hoursHint}</p>
                )}
                {errors.maxHoursPerWeek && <p id="teacher-max-hours-per-week-error" className="mt-1 text-xs font-medium text-red-700">{errors.maxHoursPerWeek.message}</p>}
              </div>

              <div>
                <label htmlFor="teacher-time-preference" className="block text-sm font-medium text-gray-700 mb-1">Time Preference</label>
                <select
                  {...register('timePreference')}
                  id="teacher-time-preference"
                  aria-invalid={errors.timePreference ? true : undefined}
                  aria-describedby={errors.timePreference ? 'teacher-time-preference-hint teacher-time-preference-error' : 'teacher-time-preference-hint'}
                  className="w-full rounded-lg border border-gray-500 bg-white px-3 py-2.5 text-base text-gray-900 shadow-sm placeholder:text-gray-500 focus:border-blue-600 sm:text-sm"
                >
                  <option value="NO_PREFERENCE">No Preference</option>
                  <option value="MORNING">Morning (08:00 - 12:00)</option>
                  <option value="AFTERNOON">Afternoon (13:00 - 17:00)</option>
                  <option value="EVENING">Evening (17:00 - 18:30)</option>
                </select>
                <p id="teacher-time-preference-hint" className="mt-1 text-xs text-gray-600">
                  A wish: Generate puts their classes at this time when it can. Times off always come first.
                </p>
                {errors.timePreference && <p id="teacher-time-preference-error" className="mt-1 text-xs font-medium text-red-700">{errors.timePreference.message}</p>}
              </div>

              <button
                type="submit"
                disabled={isSubmitting}
                className="mt-4 w-full rounded-lg bg-blue-600 px-4 py-2.5 text-sm font-semibold text-white shadow-sm transition-colors hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {isSubmitting ? 'Saving...' : editing ? 'Save Changes' : 'Save Teacher'}
              </button>
              {editing && (
                <button
                  type="button"
                  onClick={cancelEdit}
                  className="w-full rounded-lg border border-gray-500 bg-white px-4 py-2.5 text-sm font-semibold text-gray-700 shadow-sm transition-colors hover:bg-gray-50"
                >
                  Cancel
                </button>
              )}
            </form>
            </>
            )}
          </div>

          {/* RIGHT COLUMN: THE DATA TABLE */}
          <div className="lg:col-span-2 bg-white rounded-xl shadow-sm border border-gray-100 overflow-hidden">
            <TableSearchBar
              title="Current Teachers"
              inputId="search-teachers"
              label="Search teachers"
              placeholder="Name or department"
              value={search}
              onChange={setSearch}
              count={searchCount(shownTeachers.length, teachers.length, search, 'teacher', 'teachers')}
            />
            
            <div className="@container overflow-x-auto">
              <table className={`w-full text-left border-collapse ${cards.table}`}>
                <thead className={cards.head}>
                  <tr className="bg-gray-50 text-gray-600 text-sm uppercase tracking-wider border-b border-gray-200">
                    <th className="p-4 font-medium">Name</th>
                    <th className="p-4 font-medium">Department</th>
                    <th className="p-4 font-medium">Max Hours</th>
                    <th className="p-4 font-medium">Availability</th>
                    <th className="p-4 font-medium text-right">Actions</th>
                  </tr>
                </thead>
                <tbody className={`divide-y divide-gray-100 text-sm ${cards.body}`}>
                  {isLoading ? (
                    <StatusRow colSpan={5} message="Loading teachers..." />
                  ) : loadError ? (
                    <StatusRow
                      colSpan={5}
                      tone="error"
                      message={`Could not load the teachers. ${loadError}`}
                      onRetry={retryLoad}
                    />
                  ) : teachers.length === 0 ? (
                    <tr>
                      <td colSpan={5} className="p-8 text-center text-gray-500">
                        No teachers found. Add one to see them here!
                      </td>
                    </tr>
                  ) : shownTeachers.length === 0 ? (
                    <NoMatchRow colSpan={5} text={noMatchText(search, 'teacher')} inputId="search-teachers" onClear={() => setSearch('')} />
                  ) : (
                    shownTeachers.map((teacher) => (
                      <tr key={teacher.id} className={`${cards.row} ${editing?.id === teacher.id || timesOffOf?.id === teacher.id ? 'bg-blue-50' : 'hover:bg-gray-50 transition-colors'}`}>
                        <td className={`${cards.title} font-medium text-gray-900`}>{teacher.name}</td>
                        <td className={`${cards.cell} text-gray-600`}>
                          <span className={cards.label}>Department</span>
                          <span>{teacher.department}</span>
                        </td>
                        <td className={`${cards.cell} text-gray-600`}>
                          <span className={cards.label}>Max Hours</span>
                          <div>
                            <span>{teacher.maxHoursPerWeek} hrs</span>
                            {teacher.weeklyHours && teacher.weeklyHours.length === 0 && (
                              <p className="mt-1 text-xs text-gray-600">No classes yet</p>
                            )}
                            {teacher.weeklyHours && teacher.weeklyHours.length > 0 && (
                              <ul className="mt-1 space-y-1 text-xs">
                                {weeklyHoursLines(teacher.weeklyHours, teacher.maxHoursPerWeek).map((line) => (
                                  <li key={line.key} className={line.over ? 'font-medium text-red-700' : 'text-gray-600'}>
                                    {line.term}: <span className="whitespace-nowrap">{line.hours}</span>
                                    {line.over && ', over the maximum'}
                                  </li>
                                ))}
                              </ul>
                            )}
                          </div>
                        </td>
                        <td className={cards.cell}>
                          <span className={cards.label}>Availability</span>
                          <div>
                            <span className="inline-block whitespace-nowrap px-2.5 py-1 text-xs font-medium rounded-full bg-blue-50 text-blue-700">
                              {teacher.timePreference.replace('_', ' ')}
                            </span>
                            <button
                              type="button"
                              onClick={() => startTimesOff(teacher)}
                              aria-label={`Times off of ${teacher.name}`}
                              className="-ml-1 mt-2 flex items-center gap-1 rounded-md px-1 py-0.5 text-sm font-medium text-blue-700 transition-colors hover:bg-blue-50"
                            >
                              <Clock className="h-4 w-4" aria-hidden="true" />
                              Times off
                            </button>
                            {(teacher.unavailability ?? []).length === 0 ? (
                              <p className="text-sm text-gray-500">None</p>
                            ) : (
                              <ul className="space-y-0.5 text-sm text-gray-600">
                                {sortTimesOff(teacher.unavailability ?? []).map((time) => (
                                  <li key={`${time.dayOfWeek}-${time.startTime}`} className="whitespace-nowrap">
                                    {timeOffLabel(time)}
                                  </li>
                                ))}
                              </ul>
                            )}
                          </div>
                        </td>
                        <td className={cards.actions}>
                          <div className={cards.buttons}>
                            <button
                              type="button"
                              onClick={() => startEdit(teacher)}
                              aria-label={`Edit ${teacher.name}`}
                              className="inline-flex items-center gap-1 rounded-md px-2 py-1.5 text-sm font-medium text-blue-700 transition-colors hover:bg-blue-50"
                            >
                              <Pencil className="h-4 w-4" aria-hidden="true" />
                              Edit
                            </button>
                            <button
                              type="button"
                              onClick={() => setToDelete(teacher)}
                              aria-label={`Delete ${teacher.name}`}
                              className="inline-flex items-center gap-1 rounded-md px-2 py-1.5 text-sm font-medium text-red-700 transition-colors hover:bg-red-50"
                            >
                              <Trash2 className="h-4 w-4" aria-hidden="true" />
                              Delete
                            </button>
                          </div>
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </div>

        </div>
      </div>
    </div>
  );
}